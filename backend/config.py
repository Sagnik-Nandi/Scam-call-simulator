def api_key() -> str:
    key = os.environ.get("GNANI_API_KEY", "").strip()
    if key:
        return key
    key_file = Path(os.environ.get("GNANI_KEY_FILE", ROOT / "api-key.txt"))
    if key_file.exists():
        return key_file.read_text(encoding="utf-8").strip()
    return ""


def ffmpeg_path() -> str:
    explicit = os.environ.get("FFMPEG")
    if explicit:
        return explicit
    found = shutil.which("ffmpeg")
    if found:
        return found
    try:  # dev fallback: binary bundled with the imageio-ffmpeg wheel
        import imageio_ffmpeg
        return imageio_ffmpeg.get_ffmpeg_exe()
    except Exception:
        return "ffmpeg"
